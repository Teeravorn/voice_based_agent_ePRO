def _json_examples() -> str:
    return "\n".join(
        f'- "{text}" -> reason "{reason}", value {value}, meta_intent {meta}, confidence {confidence}'
        for text, reason, value, meta, confidence in FEW_SHOT_EXAMPLES
    )


def _logit_examples() -> str:
    return "\n".join(f'- "{text}" -> {value}' for text, _, value, _, _ in FEW_SHOT_EXAMPLES)


