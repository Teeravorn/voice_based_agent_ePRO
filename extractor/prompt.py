"""System prompt และ JSON schema สำหรับให้ LLM แปลงคำตอบภาษาพูดเป็นคะแนน

## ทำไม schema ถึงสำคัญกว่าที่คิด

structured output ของ Ollama/vLLM ใช้ constrained decoding คือบังคับให้โมเดลสร้าง token
ตามลำดับ field ที่ประกาศไว้ใน schema ผลคือ **ลำดับ field ในไฟล์นี้ = ลำดับความคิดของโมเดล**

1. ``reason`` ต้องมาก่อน ``value`` ถ้าสลับกัน โมเดลต้องฟันธงคะแนนเป็น token แรก
   โดยยังไม่ได้ประมวลผลอะไรเลย แล้วค่อยเขียนเหตุผลมาแก้ตัวทีหลัง
2. ``reason`` ต้องมี ``minLength`` ถ้าปล่อยให้เป็น ``""`` ได้ decoder จะปิดสตริงทันที
   (เพราะเป็นทางที่สั้นที่สุดที่ยัง valid) แล้วก็ไม่เหลืออะไรให้ยึดตอนเลือก value

ทั้งสองข้อนี้ไม่ใช่เรื่องความสวยงามของโครงสร้าง แต่กระทบความแม่นโดยตรง
วัดผลด้วย ``main.py --mode text`` ก่อนแก้ค่าพวกนี้เสมอ
"""

from __future__ import annotations

from .forms import Item, Scale

# คะแนนพิเศษ: แปลงคำตอบเป็นคะแนนไม่ได้ (ไม่ใช่ระดับอาการ)
UNDECIDED = 0

# ความยาวขั้นต่ำของเหตุผล ดูคำอธิบายด้านบนว่าทำไมต้องบังคับ
REASON_MIN_CHARS = 20

# เจตนาของผู้ป่วยที่ไม่ใช่การตอบคำถาม
# POC นี้เอาเท่าที่ extractor ตัดสินได้เอง ส่วน back/skip/stop เป็นหน้าที่ของ
# dialogue manager ซึ่งยังไม่มีในเฟสนี้
META_INTENTS = ("repeat", "dont_know", "need_help", "out_of_scope")

SYSTEM_PROMPT = """คุณเป็นผู้ช่วยของพยาบาล ทำหน้าที่แปลงคำตอบภาษาพูดของผู้ป่วยไทย ให้เป็นคะแนนตามแบบสอบถามประเมินผลการรักษามาตรฐาน

หน้าที่ของคุณคือ **จัดคำตอบของผู้ป่วยเข้ากับตัวเลือกที่ใกล้เคียงที่สุด** ผู้ป่วยส่วนใหญ่ไม่ได้พูดชื่อตัวเลือกออกมาตรง ๆ แต่จะเล่าอาการ หรือเล่าว่าทำอะไรได้แค่ไหน คุณต้องเทียบสิ่งที่ผู้ป่วยเล่ากับคำอธิบายของแต่ละตัวเลือก แล้วเลือกตัวที่ใกล้เคียงที่สุด

กฎการทำงาน
1. **เกือบทุกคำตอบเลือกได้** ถ้าคำตอบบอกเป็นนัยว่าอาการอยู่ระดับไหน ให้เลือกตัวเลือกนั้น
   - "ต้องให้ลูกหลานทำให้ทุกครั้ง" = ทำเองไม่ได้ ให้เลือกระดับสูงสุด
   - "ทำได้แต่ต้องพักบ่อย" หรือ "ทำได้แต่ช้าลง" = ระดับกลาง
   - "เหมือนเดิมทุกอย่าง" "สบายดี" "ไม่มีอะไร" = ระดับต่ำสุด
   - ถ้าผู้ป่วยพูดตัวเลข ("สาม" "ข้อ 4" "ให้ห้า") ให้ถือว่าเป็นหมายเลขตัวเลือกที่เลือก
2. **value = 0 เป็นทางเลือกสุดท้าย** ใช้เฉพาะเมื่อคำตอบไม่มีข้อมูลเรื่องระดับอาการเลยจริง ๆ
   ถ้าลังเลระหว่างสองระดับ ให้เลือกระดับที่ใกล้เคียงกว่าแล้วลด confidence ลง ห้ามตอบ 0
3. **ระวังประโยคปฏิเสธซ้อน** เช่น "ไม่ได้ปวดมากเท่าเมื่อก่อน แต่ก็ยังมีอยู่บ้าง" หมายถึงยังมีอาการ
   ระดับเบา ไม่ใช่ไม่มีอาการ ให้ตัดสินจากสภาพ "ตอนนี้" ไม่ใช่การเปรียบเทียบกับอดีต
4. อย่าประเมินให้รุนแรงเกินกว่าที่ผู้ป่วยพูด เลือกระดับสูงสุดต่อเมื่อผู้ป่วยบอกว่าทำไม่ได้เลย
   ต้องให้คนอื่นทำแทน หรือทนไม่ไหวจริง ๆ
5. ข้อความถอดมาจากเสียงพูด อาจสะกดผิดหรือมีคำซ้ำ ให้ตีความตามความหมายที่ผู้ป่วยน่าจะสื่อ
6. ถ้าผู้ป่วยไม่ได้ตอบคำถาม แต่กำลังขอสิ่งอื่น ให้ตั้ง meta_intent ให้ตรง และตั้ง value = 0
   - repeat = ขอให้ทวนคำถาม / ฟังไม่ชัด / ถามว่าเมื่อกี้ถามอะไร
   - need_help = ไม่เข้าใจคำถาม ขอคำอธิบาย
   - dont_know = ไม่รู้ ไม่แน่ใจ จำไม่ได้ หรือไม่เคยทำกิจกรรมนั้น
   - out_of_scope = พูดเรื่องอื่นที่ไม่เกี่ยวกับคำถามเลย
   - none = ตอบคำถามตามปกติ (ใช้กับเกือบทุกกรณี)
7. confidence คือความมั่นใจของคุณเอง ระหว่าง 0.0 ถึง 1.0 อย่าให้สูงเกินจริง

ลำดับการตอบ: เขียน reason ก่อน แล้วค่อยสรุปเป็น value

ตัวอย่าง (สมมติใช้ตัวเลือก 1 = ไม่มี, 2 = เล็กน้อย, 3 = ปานกลาง, 4 = รุนแรง, 5 = รุนแรงมากที่สุด)
- "ตอนนี้ไม่ปวดแล้วครับ หายดีแล้ว" -> reason "บอกว่าหายแล้ว ไม่มีอาการเหลืออยู่", value 1, meta_intent none, confidence 0.95
- "ก็ปวดนิดหน่อยเวลายกของ" -> reason "ใช้คำว่านิดหน่อย และเป็นเฉพาะตอนยกของ", value 2, meta_intent none, confidence 0.9
- "ปวดตอนเช้า ๆ แต่พอสายก็หาย" -> reason "ปวดเป็นบางช่วงแล้วหายเอง ถือว่าเล็กน้อย", value 2, meta_intent none, confidence 0.75
- "ปวดตลอดเวลา กินยาก็ไม่ดีขึ้น" -> reason "ปวดต่อเนื่องและยาไม่ช่วย ถือว่ารุนแรงที่สุด", value 5, meta_intent none, confidence 0.8
- "เมื่อกี้ถามว่าอะไรนะคะ" -> reason "ผู้ป่วยขอให้ทวนคำถาม ไม่ได้ตอบอาการ", value 0, meta_intent repeat, confidence 0.9
- "ลูกสาวพามาโรงพยาบาลเมื่อวานค่ะ" -> reason "พูดเรื่องอื่น ไม่ได้บอกระดับอาการเลย", value 0, meta_intent out_of_scope, confidence 0.8

ตอบเป็น JSON ตามโครงสร้างที่กำหนดเท่านั้น ห้ามมีข้อความอื่นนอก JSON"""


def build_schema(scale: Scale) -> dict:
    """JSON schema ที่บังคับให้โมเดลตอบเฉพาะค่าที่เป็นไปได้ของ scale นี้

    ลำดับของ ``properties`` และ ``minLength`` ของ ``reason`` มีผลต่อความแม่น
    อ่านคำอธิบายที่หัวไฟล์ก่อนแก้
    """
    return {
        "type": "object",
        "properties": {
            "reason": {
                "type": "string",
                "minLength": REASON_MIN_CHARS,
                "description": "เหตุผลสั้น ๆ เป็นภาษาไทยว่าตัดสินจากคำไหนในคำตอบของผู้ป่วย",
            },
            "value": {
                "type": "integer",
                "enum": [UNDECIDED, *scale.values],
                "description": "คะแนนที่เลือก หรือ 0 เมื่อคำตอบไม่มีข้อมูลเรื่องระดับอาการเลย",
            },
            "meta_intent": {
                "type": "string",
                "enum": ["none", *META_INTENTS],
            },
            "confidence": {"type": "number", "minimum": 0.0, "maximum": 1.0},
        },
        "required": ["reason", "value", "meta_intent", "confidence"],
        "additionalProperties": False,
    }


def build_user_prompt(transcript: str, item: Item, scale: Scale) -> str:
    """ประกอบคำถาม + ตัวเลือกทั้งหมด + คำตอบของผู้ป่วย เป็น user message เดียว

    ใส่ ``description_th`` ของทุกตัวเลือกลงไปด้วย เพราะนั่นคือสิ่งที่โมเดลต้องใช้เทียบ
    กับสิ่งที่ผู้ป่วยเล่า ส่วน ``aliases`` ไม่ใส่ เพื่อไม่ให้โมเดลเปลี่ยนไปจับคู่คำแบบ
    ตรงตัวอักษรแทนการเข้าใจความหมาย
    """
    lines = [f"คำถาม: {item.text_th}", "", "ตัวเลือกที่เลือกได้:"]
    for option in scale.options:
        lines.append(f"  {option.value} = {option.label_th} : {option.description_th}")
    lines += [
        f"  {UNDECIDED} = แปลงเป็นคะแนนไม่ได้",
        "",
        f'คำตอบของผู้ป่วย (ถอดจากเสียงพูด): "{transcript.strip()}"',
    ]
    return "\n".join(lines)
