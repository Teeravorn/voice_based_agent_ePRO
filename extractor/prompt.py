LOGIT_SYSTEM_PROMPT = f"""{_INTRO}

{_RULES}

{_EXAMPLE_HEADER}
{_logit_examples()}

ตอบด้วยตัวเลขของตัวเลือกเพียงตัวเดียว ห้ามมีคำอธิบาย ห้ามมีข้อความอื่นใดนอกจากตัวเลขนั้น"""


def build_schema(scale: Scale) -> dict:
    """JSON schema ที่บังคับให้โมเดลตอบเฉพาะค่าที่เป็นไปได้ของ scale นี้

    ลำดับของ ``properties`` และ ``minLength`` ของ ``reason`` มีผลต่อความแม่น
    อ่านคำอธิบายที่หัวไฟล์ก่อนแก้
    """
    return {
        "type": "object",
        "properties": {
            "reason": {
                "type": "string",
                "minLength": REASON_MIN_CHARS,
                "description": "เหตุผลสั้น ๆ เป็นภาษาไทยว่าตัดสินจากคำไหนในคำตอบของผู้ป่วย",
            },
            "value": {
                "type": "integer",
                "enum": [UNDECIDED, *scale.values],
                "description": "คะแนนที่เลือก หรือ 0 เมื่อคำตอบไม่มีข้อมูลเรื่องระดับอาการเลย",
            },
            "meta_intent": {
                "type": "string",
                "enum": ["none", *META_INTENTS],
            },
            "confidence": {"type": "number", "minimum": 0.0, "maximum": 1.0},
        },
        "required": ["reason", "value", "meta_intent", "confidence"],
        "additionalProperties": False,
    }


def build_user_prompt(transcript: str, item: Item, scale: Scale) -> str:
    """ประกอบคำถาม + ตัวเลือกทั้งหมด + คำตอบของผู้ป่วย เป็น user message เดียว

    ใส่ ``description_th`` ของทุกตัวเลือกลงไปด้วย เพราะนั่นคือสิ่งที่โมเดลต้องใช้เทียบ
    กับสิ่งที่ผู้ป่วยเล่า ส่วน ``aliases`` ไม่ใส่ เพื่อไม่ให้โมเดลเปลี่ยนไปจับคู่คำแบบ
    ตรงตัวอักษรแทนการเข้าใจความหมาย
    """
    lines = [f"คำถาม: {item.text_th}", "", "ตัวเลือกที่เลือกได้:"]
    for option in scale.options:
        lines.append(f"  {option.value} = {option.label_th} : {option.description_th}")
    lines += [
        f"  {UNDECIDED} = แปลงเป็นคะแนนไม่ได้",
        "",
        f'คำตอบของผู้ป่วย (ถอดจากเสียงพูด): "{transcript.strip()}"',
    ]
    return "\n".join(lines)
